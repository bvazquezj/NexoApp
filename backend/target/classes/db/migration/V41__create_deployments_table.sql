CREATE TABLE deployments (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES users(id),
    project_id UUID NOT NULL REFERENCES projects(id),
    name VARCHAR(100) NOT NULL,
    environment VARCHAR(10) NOT NULL CHECK (environment IN ('DEV','STAGING','PROD')),
    platform VARCHAR(20) NOT NULL CHECK (platform IN ('VERCEL','RENDER','FLYIO','AWS','RAILWAY','NETLIFY','OTHER')),
    platform_label VARCHAR(50),
    url TEXT NOT NULL,
    repo_url TEXT,
    branch VARCHAR(200),
    version VARCHAR(100),
    status VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN' CHECK (status IN ('UNKNOWN','DEPLOYING','ACTIVE','DEGRADED','DOWN','INACTIVE')),
    hook_token UUID UNIQUE NOT NULL DEFAULT gen_random_uuid(),
    health_check_enabled BOOLEAN NOT NULL DEFAULT true,
    health_check_interval_minutes INTEGER NOT NULL DEFAULT 5 CHECK (health_check_interval_minutes >= 1 AND health_check_interval_minutes <= 60),
    notify_on_down BOOLEAN NOT NULL DEFAULT true,
    notify_on_recovery BOOLEAN NOT NULL DEFAULT true,
    notify_on_degraded BOOLEAN NOT NULL DEFAULT false,
    last_email_sent_at TIMESTAMPTZ,
    platform_api_token_encrypted TEXT,
    platform_service_id VARCHAR(200),
    notes VARCHAR(500),
    last_deployed_at TIMESTAMPTZ,
    last_health_check_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
