CREATE TABLE domains (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES users(id),
    client_id UUID REFERENCES clients(id),
    project_id UUID REFERENCES projects(id),
    name VARCHAR(100) NOT NULL,
    tld VARCHAR(20) NOT NULL,
    full_domain VARCHAR(255) NOT NULL,
    registrar VARCHAR(20) NOT NULL CHECK (registrar IN ('DONDOMINIO','GODADDY','NAMECHEAP','CLOUDFLARE','GOOGLE','IONOS','AWS','SQUARESPACE','OTHER')),
    registrar_label VARCHAR(50),
    dns_provider VARCHAR(20) CHECK (dns_provider IS NULL OR dns_provider IN ('CLOUDFLARE','VERCEL','RENDER','GODADDY','NAMECHEAP','AWS_ROUTE53','IONOS','OTHER')),
    dns_provider_label VARCHAR(50),
    registered_at DATE,
    expires_at DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','TRANSFERRED','RELEASED')),
    whois_privacy BOOLEAN NOT NULL DEFAULT false,
    auto_renewal BOOLEAN NOT NULL DEFAULT false,
    renewal_price_amount DECIMAL(10,2),
    renewal_price_currency VARCHAR(5) CHECK (renewal_price_currency IS NULL OR renewal_price_currency IN ('MXN','USD')),
    notes TEXT,
    last_checked_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
